func TestPollAchieved(t *testing.T) {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /v2/events", func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Query().Get("since") != "4" || r.URL.Query().Get("type") != "ACHIEVED" {
			t.Errorf("query = %s", r.URL.RawQuery)
		}
		w.Write([]byte(`{"events":[{"seq":9,"intent_seq":6,"intent_id":"aa","type":"ACHIEVED","idempotency_key":"k","trajectory_hash":"th"}],"next_since":9}`))
	})
	srv := httptest.NewServer(mux)
	t.Cleanup(srv.Close)
	c := &Client{BaseURL: srv.URL}
	recs, next, err := c.PollAchieved(context.Background(), 4)
	if err != nil {
		t.Fatal(err)
	}
	if len(recs) != 1 || recs[0].IdempotencyKey != "k" || next != 9 {
		t.Fatalf("recs=%+v next=%d", recs, next)
	}
}
